"""Record the "how to use" tutorial video for the app.

Drives the real app in Chrome with Playwright (uploads, generates, brushes,
chats, renders a camera move), takes a screenshot at every step, then builds
an MP4: each scene spotlights the part being explained, with an English
voice-over (macOS `say`) and subtitles.

    .venv/bin/pip install playwright        # uses the installed Google Chrome
    .venv/bin/uvicorn app.main:app --port 8765
    .venv/bin/python docs/tutorial/make_tutorial.py

Uses about 2-3 edits of the Cloudflare daily allowance (one manual edit and
one chat-agent edit). Output: docs/tutorial/archedit-tutorial.mp4
"""

from __future__ import annotations

import argparse
import subprocess
import tempfile
import wave
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

import imageio_ffmpeg
import numpy as np
from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "archedit-tutorial.mp4"
PREVIEW = OUT.with_suffix(".gif")  # silent, auto-playing copy for the README
VIEW_W, VIEW_H = 1440, 900  # browser viewport
OUT_W, OUT_H = 1280, 800  # video size
FPS = 30
FADE = 12  # crossfade frames between scenes
VOICE, RATE = "Samantha", 178
ACCENT = (214, 16, 110)
FONT = "/System/Library/Fonts/HelveticaNeue.ttc"

Box = tuple[float, float, float, float]  # x, y, w, h in viewport pixels


@dataclass
class Scene:
    text: str
    image: Optional[Path] = None
    boxes: list[Box] = field(default_factory=list)
    clip: Optional[Path] = None  # play this MP4 full frame instead of a screenshot
    speech: Optional[str] = None  # what the voice says, when it differs from the subtitle
    pair: Optional[tuple[Path, Path, tuple[float, float, float, float]]] = None  # before, after, crop (fractions)


# ---------------------------------------------------------------------------
# 1. Drive the app and capture the scenes
# ---------------------------------------------------------------------------

def record(url: str, work: Path) -> list[Scene]:
    from playwright.sync_api import sync_playwright

    scenes: list[Scene] = []
    with sync_playwright() as p:
        browser = p.chromium.launch(channel="chrome", headless=True)
        ctx = browser.new_context(viewport={"width": VIEW_W, "height": VIEW_H}, device_scale_factor=1,
                                  color_scheme="light")
        page = ctx.new_page()

        def box(selector: str) -> Box:
            b = page.locator(selector).first.bounding_box()
            return (b["x"], b["y"], b["width"], b["height"])

        def shot(text: str, *selectors: str, scroll_to: Optional[str] = None, top: bool = False) -> None:
            if top:
                page.evaluate("window.scrollTo(0, 0)")
                page.wait_for_timeout(400)
            if scroll_to:
                page.locator(scroll_to).first.scroll_into_view_if_needed()
                page.wait_for_timeout(400)
            path = work / f"scene{len(scenes):02d}.png"
            page.screenshot(path=str(path))
            speech = text.replace("FLUX.2", "Flux 2").replace("FLUX", "Flux")
            scenes.append(Scene(text=text, image=path, boxes=[box(s) for s in selectors], speech=speech))
            print(f"scene {len(scenes)}: {text[:60]}")

        def wait_enabled(selector: str, timeout: float = 240_000) -> None:
            page.wait_for_function(f"!document.querySelector('{selector}').disabled", timeout=timeout)

        page.goto(url)
        page.wait_for_function("document.getElementById('statusPill').textContent.includes('Cloudflare')")
        page.wait_for_timeout(1500)
        shot("This is Image editing for architecture: a tool for editing architecture and interior images. "
             "Pictures are generated by FLUX.2 on Cloudflare's free daily allowance.")

        page.click("#tools [data-k=edit]")
        page.wait_for_timeout(1500)
        shot("Start with a photo. Click Upload image, or drag a picture onto the Input box. "
             "Here we use the sample bedroom.", "#drop", "#upload")
        shot("On the left, pick a tool: Image edit, Sketch to render, Materials, Lighting, or Style and staging.",
             "#tools")

        page.click("#tools [data-k=lighting]")
        page.wait_for_timeout(800)
        page.get_by_role("button", name="Golden hour").click()
        shot("Each tool has presets with prompts written for that job. "
             "Choose Lighting and time, then Golden hour. You can also edit the prompt yourself.",
             "#presets", "#prompt")

        page.click("#generate")
        page.wait_for_timeout(500)
        wait_enabled("#generate")
        page.wait_for_timeout(1500)
        shot("Press Generate. A few seconds later the result appears. "
             "The drift guard re-aligns it to the input, and shows how many pixels it corrected.",
             "#outImg", "#outInfo", top=True)

        page.locator("#comparePanel").scroll_into_view_if_needed()
        cmp = page.locator("#compare").bounding_box()
        page.mouse.move(cmp["x"] + cmp["width"] * 0.5, cmp["y"] + cmp["height"] / 2)
        page.mouse.down()
        page.mouse.move(cmp["x"] + cmp["width"] * 0.42, cmp["y"] + cmp["height"] / 2, steps=8)
        page.mouse.up()
        shot("Drag the before and after slider to compare the result with the original, or with the previous round.",
             "#compare", scroll_to="#comparePanel")
        shot("Every result becomes the input of the next round, so edits stack up. "
             "Rounds lets you undo, redo, or branch from any earlier step.",
             "#roundsPanel", scroll_to="#roundsPanel")

        # Brush the blue kitchen wall in Materials.
        page.evaluate("window.scrollTo(0, 0)")
        page.click("#tools [data-k=materials]")
        page.wait_for_timeout(1200)
        page.evaluate("document.getElementById('brush').value = 30")
        canvas = page.locator("#srcCanvas")
        cb = canvas.bounding_box()
        nat = page.evaluate("[document.getElementById('srcCanvas').width, document.getElementById('srcCanvas').height]")
        s = min(cb["width"] / nat[0], cb["height"] / nat[1])
        ox, oy = cb["x"] + (cb["width"] - nat[0] * s) / 2, cb["y"] + (cb["height"] - nat[1] * s) / 2
        k = nat[0] / 768  # the sample photo is laid out for 768 px wide

        def at(x: float, y: float) -> tuple[float, float]:
            return ox + x * k * s, oy + y * k * s

        for y in range(205, 290, 14):
            page.mouse.move(*at(705, y))
            page.mouse.down()
            page.mouse.move(*at(762, y), steps=6)
            page.mouse.up()
        shot("To change only one part, use Materials, or switch any tool to Brushed area, "
             "and paint over it. Here we brush the blue kitchen wall. Pixels outside the brush never change.",
             "#drop", "#targetBox", scroll_to="#drop")

        page.locator("#agentPanel").scroll_into_view_if_needed()
        page.fill("#agentMsg", "Change this blue wall to white marble with thin gold veins")
        shot("Or just ask the chat editing agent. It is built with LangGraph. "
             "Describe one or several changes in any language. Brushed area is on, so it edits only the painted wall.",
             "#agentPanel", scroll_to="#agentPanel")
        page.press("#agentMsg", "Enter")
        page.wait_for_timeout(1000)
        wait_enabled("#agentSend")
        page.wait_for_timeout(1500)
        shot("The agent plans the steps, edits round by round, and checks every result with a vision model. "
             "A missed edit is retried once. Follow-up messages keep editing from the latest round.",
             "#chatLog", scroll_to="#chatLog")
        rounds = page.evaluate("[...document.querySelectorAll('#rounds img')].map(i => i.getAttribute('src'))")
        text = "Here is the result, close up: the wall is now marble, and the rest of the photo is untouched."
        scenes.append(Scene(text=text, pair=(ROOT / rounds[-2].lstrip("/"), ROOT / rounds[-1].lstrip("/"),
                                             (0.52, 0.12, 1.0, 0.72))))
        print(f"scene {len(scenes)}: {text[:60]}")

        page.locator("#videoPanel").scroll_into_view_if_needed()
        page.click("#motions [data-k=orbit]")
        page.click("#makeVideo")
        page.wait_for_timeout(500)
        wait_enabled("#makeVideo")
        page.wait_for_timeout(1500)
        shot("Finally, Camera-move video turns the current round into a short clip. "
             "Pick Push in, Pan or Orbit, and press Make video. It runs on your own computer, for free.",
             "#videoPanel", scroll_to="#videoPanel")
        video_url = page.evaluate("document.getElementById('videoPlayer').getAttribute('src')")
        scenes.append(Scene(
            text="A depth model estimates how far away every pixel is, so near objects move more than far ones.",
            clip=ROOT / video_url.lstrip("/")))
        shot("Tick Bigger move for a larger camera move. "
             "The areas it reveals behind objects are repainted by FLUX, using one or two edits.",
             "#fillBox", scroll_to="#videoPanel")

        page.evaluate("window.scrollTo(0, 0)")
        page.wait_for_timeout(500)
        shot("That's it: upload, edit in rounds, chat with the agent, and make a camera move. Have fun designing!")
        browser.close()
    return scenes


# ---------------------------------------------------------------------------
# 2. Voice-over
# ---------------------------------------------------------------------------

def speak(text: str, path: Path) -> np.ndarray:
    """Mono 16-bit samples at 44.1 kHz of the text read by the macOS voice."""
    aiff = path.with_suffix(".aiff")
    subprocess.run(["say", "-v", VOICE, "-r", str(RATE), "-o", str(aiff), text], check=True)
    subprocess.run([imageio_ffmpeg.get_ffmpeg_exe(), "-y", "-loglevel", "error", "-i", str(aiff),
                    "-ac", "1", "-ar", "44100", str(path)], check=True)
    with wave.open(str(path)) as w:
        return np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16)


# ---------------------------------------------------------------------------
# 3. Frames
# ---------------------------------------------------------------------------

def font(size: int) -> ImageFont.FreeTypeFont:
    return ImageFont.truetype(FONT, size, index=0)


def wrap(text: str, f: ImageFont.FreeTypeFont, width: int) -> list[str]:
    lines, line = [], ""
    for word in text.split():
        trial = f"{line} {word}".strip()
        if f.getlength(trial) <= width:
            line = trial
        else:
            lines.append(line)
            line = word
    return lines + [line] if line else lines


def spotlight(img: Image.Image, boxes: list[Box], strength: float) -> Image.Image:
    """Dim everything except the boxes and outline them in the accent colour."""
    if not boxes or strength <= 0:
        return img
    mask = Image.new("L", img.size, 0)
    d = ImageDraw.Draw(mask)
    pad = 8
    for x, y, w, h in boxes:
        d.rounded_rectangle((x - pad, y - pad, x + w + pad, y + h + pad), radius=10, fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(3))
    dim = Image.blend(img, Image.new("RGB", img.size, (0, 0, 0)), 0.45 * strength)
    out = Image.composite(img, dim, mask)
    d = ImageDraw.Draw(out)
    for x, y, w, h in boxes:
        d.rounded_rectangle((x - pad, y - pad, x + w + pad, y + h + pad), radius=10,
                            outline=ACCENT, width=max(1, round(4 * strength)))
    return out


def caption(frame: Image.Image, text: str) -> Image.Image:
    f = font(30)
    lines = wrap(text, f, OUT_W - 160)
    band_h = 34 + 42 * len(lines)
    band = Image.new("RGBA", (OUT_W, band_h), (12, 12, 14, 200))
    frame = frame.convert("RGBA")
    frame.alpha_composite(band, (0, OUT_H - band_h))
    d = ImageDraw.Draw(frame)
    for i, line in enumerate(lines):
        d.text((OUT_W / 2, OUT_H - band_h + 17 + 42 * i), line, font=f, fill="white", anchor="ma")
    return frame.convert("RGB")


def pair_frame(scene: Scene) -> Image.Image:
    """Before | After crops of the same area, full frame, labelled."""
    before, after, (x0, y0, x1, y1) = scene.pair
    canvas = Image.new("RGB", (OUT_W, OUT_H), (18, 18, 20))
    d = ImageDraw.Draw(canvas)
    gap, top = 24, 70
    tile_w = (OUT_W - 3 * gap) // 2
    for i, (label, path) in enumerate((("Before", before), ("After", after))):
        im = Image.open(path).convert("RGB")
        W, H = im.size
        crop = im.crop((round(x0 * W), round(y0 * H), round(x1 * W), round(y1 * H)))
        crop.thumbnail((tile_w, OUT_H - top - 150), Image.LANCZOS)
        x = gap + i * (tile_w + gap) + (tile_w - crop.width) // 2
        canvas.paste(crop, (x, top))
        d.text((x, top - 46), label, font=font(30), fill=ACCENT if i else "white")
    return canvas


def scene_frames(scene: Scene, n: int):
    """Yield n frames: a slow zoom toward the highlighted area with the spotlight fading in."""
    if scene.pair is not None:
        frame = caption(pair_frame(scene), scene.text)
        for _ in range(n):
            yield frame
        return
    if scene.clip is not None:
        gen = imageio_ffmpeg.read_frames(str(scene.clip))
        meta = next(gen)
        w, h = meta["size"]
        clip = [Image.frombytes("RGB", (w, h), f) for f in gen]
        for i in range(n):
            src = clip[i % len(clip)]  # loop the clip under the narration
            canvas = Image.new("RGB", (OUT_W, OUT_H), (18, 18, 20))
            fit = src.copy()
            fit.thumbnail((OUT_W - 80, OUT_H - 150))
            canvas.paste(fit, ((OUT_W - fit.width) // 2, 30))
            yield caption(canvas, scene.text)
        return
    base = Image.open(scene.image).convert("RGB")
    if scene.boxes:
        xs = [x + w / 2 for x, y, w, h in scene.boxes]
        ys = [y + h / 2 for x, y, w, h in scene.boxes]
        cx, cy = sum(xs) / len(xs), sum(ys) / len(ys)
    else:
        cx, cy = VIEW_W / 2, VIEW_H / 2
    cache = {}
    for i in range(n):
        t = i / max(1, n - 1)
        strength = min(1.0, i / 15)
        key = round(strength, 2)
        if key not in cache:
            cache[key] = spotlight(base, scene.boxes, strength)
        lit = cache[key]
        zoom = 1.0 + 0.035 * t * t * (3 - 2 * t)
        cw, ch = VIEW_W / zoom, VIEW_H / zoom
        left = min(max(cx - cw / 2, 0), VIEW_W - cw)
        top = min(max(cy - ch / 2, 0), VIEW_H - ch)
        frame = lit.resize((OUT_W, OUT_H), Image.LANCZOS, box=(left, top, left + cw, top + ch))
        yield caption(frame, scene.text)


def build(scenes: list[Scene], work: Path, out: Path) -> None:
    rate = 44100
    audio_parts, plan = [], []
    for i, sc in enumerate(scenes):
        voice = speak(sc.speech or sc.text, work / f"voice{i:02d}.wav")
        secs = len(voice) / rate + 0.9  # breathing room after each line
        n = round(secs * FPS)
        plan.append(n)
        lead = np.zeros(int(0.25 * rate), np.int16)
        part = np.concatenate([lead, voice])
        total = int(n / FPS * rate)
        audio_parts.append(np.pad(part, (0, max(0, total - len(part))))[:total])
    audio = np.concatenate(audio_parts)
    audio_path = work / "voice.wav"
    with wave.open(str(audio_path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(audio.tobytes())

    writer = imageio_ffmpeg.write_frames(
        str(out), (OUT_W, OUT_H), fps=FPS, codec="libx264", pix_fmt_out="yuv420p", quality=None,
        macro_block_size=16, audio_path=str(audio_path), audio_codec="aac",
        # Mostly still screenshots: a high CRF with the still-image tune keeps text sharp and the file small.
        output_params=["-crf", "26", "-preset", "slow", "-tune", "stillimage", "-b:a", "96k",
                       "-movflags", "+faststart", "-shortest"],
        ffmpeg_log_level="error",
    )
    writer.send(None)
    prev_last: Optional[np.ndarray] = None
    for sc, n in zip(scenes, plan):
        for j, frame in enumerate(scene_frames(sc, n)):
            arr = np.asarray(frame)
            if prev_last is not None and j < FADE:  # crossfade from the previous scene
                a = (j + 1) / (FADE + 1)
                arr = (prev_last * (1 - a) + arr * a).astype(np.uint8)
            writer.send(np.ascontiguousarray(arr))
            last = arr
        prev_last = last.astype(np.float32)
    writer.close()
    start = 0
    for sc, n in zip(scenes, plan):
        print(f"  {start / FPS:6.1f}s  {sc.text[:70]}")
        start += n
    print(f"wrote {out} ({sum(plan) / FPS:.0f} s, {out.stat().st_size / 1e6:.1f} MB)")


def make_preview(video: Path, out: Path, width: int = 640, sample_fps: int = 4, min_change: float = 10.0) -> None:
    """Silent animated GIF of the tutorial for the README, where GIFs play on their own and
    videos don't. Frames that barely change are merged into one longer frame, so the long
    still scenes cost almost nothing and the file stays small."""
    gen = imageio_ffmpeg.read_frames(str(video))
    meta = next(gen)
    w, h = meta["size"]
    step = round(FPS / sample_fps)
    height = round(h * width / w)
    frames: list[Image.Image] = []
    durations: list[int] = []
    last: Optional[np.ndarray] = None
    for i, raw in enumerate(gen):
        if i % step:
            continue
        img = Image.frombytes("RGB", (w, h), raw).resize((width, height), Image.LANCZOS)
        arr = np.asarray(img, dtype=np.int16)
        small = img.quantize(colors=160, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
        if last is not None and np.abs(arr - last).mean() < min_change:
            # Same scene: keep showing it longer, and keep its latest look (spotlight fully on).
            durations[-1] += round(1000 / sample_fps)
            frames[-1] = small
        else:
            frames.append(small)
            durations.append(round(1000 / sample_fps))
        last = arr
    frames[0].save(out, save_all=True, append_images=frames[1:], duration=durations, loop=0, optimize=True)
    print(f"wrote {out} ({len(frames)} frames, {out.stat().st_size / 1e6:.1f} MB)")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default="http://localhost:8765")
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--keep", type=Path, help="keep the screenshots and voice files in this folder")
    ap.add_argument("--preview-only", action="store_true", help="only rebuild the README GIF from the MP4")
    args = ap.parse_args()
    if args.preview_only:
        make_preview(args.out, args.out.with_suffix(".gif"))
        return
    with tempfile.TemporaryDirectory() as tmp:
        work = args.keep or Path(tmp)
        work.mkdir(parents=True, exist_ok=True)
        scenes = record(args.url, work)
        build(scenes, work, args.out)
    make_preview(args.out, args.out.with_suffix(".gif"))


if __name__ == "__main__":
    main()
